const { generateImage } = require("../services/unit-services/glmImageService");
const { uploadBufferToSpaces } = require("../utils/s3Uploader");
const fetch = require("node-fetch");

exports.generateGlmImage = async (req, res) => {
  const { prompt, viewMode = "square" } = req.body;

  if (!prompt) {
    return res.status(400).json({ error: "Prompt is required." });
  }

  try {
    const imageUrl = await generateImage(prompt, viewMode);
    
    console.log(`Image generated by Z.AI: ${imageUrl}`);
    console.log("Uploading to S3...");
    
    // Fetch the image from Z.AI and upload to S3 with retry mechanism
    let imageResponse;
    let retries = 3;
    while (retries > 0) {
      imageResponse = await fetch(imageUrl);
      if (imageResponse.ok) break;
      
      const errorText = await imageResponse.text();
      console.warn(`Attempt failed to fetch image from Z.AI. Status: ${imageResponse.status}. Retries left: ${retries - 1}`);
      
      retries--;
      if (retries > 0) {
        await new Promise(resolve => setTimeout(resolve, 1500)); // Wait 1.5s before retry
      } else {
        throw new Error(`Failed to fetch image from Z.AI after multiple attempts (Status: ${imageResponse.status})`);
      }
    }
    
    const buffer = await imageResponse.buffer();
    const filename = `glm-infographic-${Date.now()}.png`;
    const s3Url = await uploadBufferToSpaces(buffer, filename, "image/png");

    console.log("Image successfully uploaded to S3:", s3Url);
    res.json({ success: true, imageUrl: s3Url });
  } catch (error) {
    console.error("GLM Image generation error:", error);
    res.status(500).json({ error: error.message || "Failed to generate image" });
  }
};
