const {
  generateImageSuggestions,
} = require("../services/generateImageSuggestions");

exports.generateImageSuggestionsHandler = async (req, res) => {
  const { prompt, count = 1 } = req.body;

  if (!prompt) {
    return res.status(400).json({ error: "Image prompt is required." });
  }

  try {
    const finalPrompt = `${prompt}

STRICT RULE:

- Ensure that the geenrated image does not have any embeded text or any letters characters in them only use the prompt as a raeference on what the image should be about, under no circumstances should the out put of the image contain any embedded Textual data
`;

    const imageUrls = await generateImageSuggestions(finalPrompt, count);

    if (imageUrls.length > 0) {
      res.json({ imageUrls });
    } else {
      res.status(500).json({ error: "No images were generated by the AI." });
    }
  } catch (err) {
    console.error("Error generating image suggestions:", err);
    res
      .status(500)
      .json({ error: "Failed to generate image suggestions: " + err.message });
  }
};
