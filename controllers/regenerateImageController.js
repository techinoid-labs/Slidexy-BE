const { uploadToSpaces } = require("../utils/s3Uploader");
const { generateImageSuggestions } = require("../services/generateImageSuggestions");

// Generate images and upload to S3
exports.generateImageSuggestionsHandler = async (req, res) => {
  const { prompt, count = 3 } = req.body;

  if (!prompt) {
    return res.status(400).json({ error: "Image prompt is required." });
  }

  try {
    const finalPrompt = `${prompt}

STRICT RULE:
- Ensure that the generated image does not have any embedded text or any letters/characters in them
- Only use the prompt as a reference on what the image should be about
- Under no circumstances should the output of the image contain any embedded textual data`;

    console.log("Generating images with prompt:", finalPrompt);
    
    // Generate base64 images
    const base64Images = await generateImageSuggestions(finalPrompt, count);

    if (!base64Images || base64Images.length === 0) {
      return res.status(500).json({ error: "No images were generated by the AI." });
    }

    console.log(`Generated ${base64Images.length} images, uploading to S3...`);

    // Upload all images to S3 in parallel
    const uploadPromises = base64Images.map(async (base64Image, index) => {
      try {
        const filename = `generated-image-${Date.now()}-${index}`;
        const s3Url = await uploadToSpaces(base64Image, filename);
        console.log(`Uploaded image ${index + 1} to S3:`, s3Url);
        return s3Url;
      } catch (uploadError) {
        console.error(`Failed to upload image ${index + 1}:`, uploadError);
        return null;
      }
    });

    const imageUrls = (await Promise.all(uploadPromises)).filter(url => url !== null);

    if (imageUrls.length > 0) {
      console.log(`✅ Successfully uploaded ${imageUrls.length} images to S3`);
      res.json({ imageUrls });
    } else {
      res.status(500).json({ error: "Failed to upload images to S3" });
    }
  } catch (err) {
    console.error("Error generating image suggestions:", err);
    res.status(500).json({ 
      error: "Failed to generate image suggestions: " + err.message 
    });
  }
};

// Upload a single base64 image to S3 (for manual uploads)
exports.uploadImageHandler = async (req, res) => {
  const { base64Image, filename } = req.body;

  if (!base64Image) {
    return res.status(400).json({ error: "Base64 image data is required" });
  }

  try {
    const finalFilename = filename || `uploaded-image-${Date.now()}`;
    const s3Url = await uploadToSpaces(base64Image, finalFilename);
    
    console.log("Image uploaded to S3:", s3Url);
    
    res.json({ 
      success: true, 
      imageUrl: s3Url 
    });
  } catch (err) {
    console.error("Error uploading image:", err);
    res.status(500).json({ 
      error: "Failed to upload image: " + err.message 
    });
  }
};

// Batch upload multiple base64 images
exports.uploadMultipleImagesHandler = async (req, res) => {
  const { images } = req.body; // Array of { base64, filename? }

  if (!images || !Array.isArray(images) || images.length === 0) {
    return res.status(400).json({ error: "Images array is required" });
  }

  try {
    const uploadPromises = images.map(async (img, index) => {
      const filename = img.filename || `batch-upload-${Date.now()}-${index}`;
      return await uploadToSpaces(img.base64, filename);
    });

    const imageUrls = await Promise.all(uploadPromises);
    
    console.log(`Batch uploaded ${imageUrls.length} images to S3`);
    
    res.json({ 
      success: true, 
      imageUrls 
    });
  } catch (err) {
    console.error("Error batch uploading images:", err);
    res.status(500).json({ 
      error: "Failed to upload images: " + err.message 
    });
  }
};